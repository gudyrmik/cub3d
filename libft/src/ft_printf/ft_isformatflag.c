#include "libft.h"

int	ft_isformatflag(char c)
{
	char	*str;
	size_t	i;

	i = 0;
	str = "-+ #0%";
	while (str[i])
	{
		if (c == str[i])
			return (1);
		i++;
	}
	return (0);
}
